          <h2>Why saying "We make anything" won't help you get specified</h2>  
          <p>Being able to fabricate almost anything is a strong offer, but only if a creative specifier can find evidence of it online and quickly assess its suitability for their scheme. The more product genres and variations shown, the easier that assessment becomes.</p>
          <p>This is where fabricators of bespoke items tend to lose ground. Bespoke items move through the workshop fast to meet deadlines, so there's rarely time to photograph them on the factory floor. Once installed on site, arranging photography takes time the supplier usually doesn't have and the result is a body of work that does not appear online. </p>
    
